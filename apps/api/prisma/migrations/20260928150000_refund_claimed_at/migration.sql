-- ============================================================================
-- استرداد عالق في processing
--
-- التنفيذ يحجز الاسترداد (pending ← processing) ثم يطلبه من البوابة ثم يسجّل
-- النتيجة. سقوط الخادم بين الحجز والتسجيل كان يتركه processing إلى الأبد:
-- مهمة الإعادة لا ترى إلا pending، والمشتري لا يصله ماله.
--
-- claimedAt يعرّف عمر الحجز: ما بقي processing أطول من مهلة التنفيذ سقط
-- منفّذه، فتعيده المهمة بحجز شرطي جديد. الإعادة آمنة لأن طلب البوابة بمفتاح
-- عدم تكرار ثابت للاسترداد — ما رُدّ من قبل يعود ردّه الأول ولا يُردّ ثانيةً.
-- ============================================================================

ALTER TABLE "refunds" ADD COLUMN "claimedAt" TIMESTAMPTZ;

CREATE INDEX "refunds_processing_claimedAt_idx" ON "refunds" ("claimedAt") WHERE "status" = 'processing';
