-- ============================================================================
-- تثبيت عملة التسوية لكل متجر تجاوز التأهيل — ADR-013
--
-- التثبيت كان اختيارياً: متجر أُرسل واعتُمد دون أن يثبّت عملته بقي قادراً على
-- تغييرها وهو يبيع، فتُقرأ أسعاره وأسعار شحنه ومحفظته بعملة أخرى. الاعتماد صار
-- يثبّتها؛ وهذا يثبّتها لمن اعتُمد قبله (ومن عُلّق أو حُظر بعد اعتماده).
-- المراجَع الآن (in_review) يثبّته اعتماده، والتأهيل (pending/rejected) مفتوح.
-- ============================================================================

UPDATE "vendors"
SET "settlementCurrencyLockedAt" = COALESCE("approvedAt", "submittedAt", now())
WHERE "settlementCurrencyLockedAt" IS NULL
  AND "status" IN ('approved', 'suspended', 'banned');
