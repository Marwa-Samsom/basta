-- ============================================================================
-- التحقق بخطوتين — سرّ التهيئة في عمود منفصل
--
-- كان بدء التهيئة يكتب السرّ الجديد فوق المفعَّل ويصفّر `totpEnabledAt`،
-- فجلسة مسروقة (أو مجرّد فتح الصفحة) تنزع الحماية عن حساب مدير. السرّ
-- الجديد يُكتب الآن هنا وحده، ولا يحلّ محلّ `totpSecretEnc` إلا بعد رمز
-- صحيح منه — وتغيير الجهاز على تحقق مفعَّل يطلب كلمة المرور ورمزاً حالياً.
-- ============================================================================

ALTER TABLE "users" ADD COLUMN "totpPendingSecretEnc" TEXT;

-- تهيئات بدأت ولم تُؤكَّد: سرّها ينتقل إلى مكانه الجديد، فيُكمل صاحبها التأكيد
UPDATE "users"
   SET "totpPendingSecretEnc" = "totpSecretEnc", "totpSecretEnc" = NULL
 WHERE "totpEnabledAt" IS NULL AND "totpSecretEnc" IS NOT NULL;
