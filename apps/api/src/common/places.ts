/**
 * مفتاح مقارنة لأسماء الأماكن — المحافظة والمدينة يكتبهما البائع في تغطيته
 * والمشتري في عنوانه، وكانت المطابقة حرفية: «عمّان» لا تطابق «عمان» و«الزرقا»
 * لا تطابق «الزرقاء»، فيُقال لمشترٍ مغطّى «لا يشحن إلى عنوانك».
 *
 * للمقارنة وحدها: الاسم يُحفظ ويُعرض كما كُتب. التوحيد قصد لا تساهل عامّ —
 * التشكيل والشدّة والتطويل، وأشكال الهمزة والألف، والتاء المربوطة والألف
 * المقصورة، وكلمة «محافظة/منطقة/إمارة/ولاية» في أوّل الاسم. نسخته في الواجهة
 * `web/src/lib/places.ts` تبقى مطابقة لها (معاينة الشحن تحسب بالقاعدة نفسها).
 */
export function placeKey(raw: string | null | undefined): string {
  return (raw ?? '')
    .normalize('NFC')
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ء/g, '')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^(محافظه|منطقه|اماره|ولايه)\s+/, '');
}

/** اسمان لمكان واحد؟ الفارغ لا يطابق إلا الفارغ */
export const samePlace = (a: string | null | undefined, b: string | null | undefined): boolean => placeKey(a) === placeKey(b);
