import { describe, expect, it } from 'vitest';
import { arabicCounts, daysAr, hoursAr } from './arabic-count';

/** العدد ومعدوده بالعربية — كانت النصوص «خلال 6 ساعة» و«منذ 11 أيام» (VOPS-019، 29 أكتوبر 2026) */
describe('العدد ومعدوده', () => {
  it('الساعات: الواحد والاثنان بلفظهما، 3–10 جمع، 11–99 مفرد، والمئة مفرد', () => {
    expect([1, 2, 3, 6, 10, 11, 24, 48, 100, 103, 111].map(hoursAr)).toEqual([
      'ساعة واحدة',
      'ساعتين',
      '3 ساعات',
      '6 ساعات',
      '10 ساعات',
      '11 ساعة',
      '24 ساعة',
      '48 ساعة',
      '100 ساعة',
      '103 ساعات',
      '111 ساعة',
    ]);
  });

  it('الأيام: «يوم واحد»، «يومين»، «4 أيام»، «14 يوماً»، «100 يوم»', () => {
    expect([1, 2, 4, 10, 11, 14, 99, 100].map(daysAr)).toEqual([
      'يوم واحد',
      'يومين',
      '4 أيام',
      '10 أيام',
      '11 يوماً',
      '14 يوماً',
      '99 يوماً',
      '100 يوم',
    ]);
  });

  it('في نصّ جاهز: يصحّح المعدود بعد الرقم ولا يمسّ غيره', () => {
    expect(arabicCounts('لم يُقبل — يُلغى آلياً خلال 9 ساعة.')).toBe('لم يُقبل — يُلغى آلياً خلال 9 ساعات.');
    expect(arabicCounts('لم يقبله البائع خلال 6 ساعة')).toBe('لم يقبله البائع خلال 6 ساعات');
    expect(arabicCounts('يُلغى بعد 2 ساعة')).toBe('يُلغى بعد ساعتين');
    expect(arabicCounts('المهلة 48 ساعة.')).toBe('المهلة 48 ساعة.');
    expect(arabicCounts('عالق منذ 4 أيام، ومنذ 11 أيام، ومنذ 1 أيام')).toBe('عالق منذ 4 أيام، ومنذ 11 يوماً، ومنذ يوم واحد');
    expect(arabicCounts('انقضت 14 يوماً')).toBe('انقضت 14 يوماً');
    // أرقام ليست عدداً لمعدود: رقم طلب ومبلغ ووقت لا تُمسّ
    expect(arabicCounts('الطلب BST-261029-AB12 بـ 12.500 د.أ الساعة 3:22')).toBe('الطلب BST-261029-AB12 بـ 12.500 د.أ الساعة 3:22');
    // «ساعة» جزء من كلمة أطول لا تُمسّ
    expect(arabicCounts('خلال 5 ساعتين')).toBe('خلال 5 ساعتين');
  });
});
